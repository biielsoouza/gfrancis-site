def traduzir(html: str) -> str:
    """Aplica a lista. Erro se algum trecho em português não estiver mais no home.html."""
    faltando = []
    for pt, en in PARES:   # em ordem: um trecho já trocado por outro par também conta como faltando
        if pt not in html:
            faltando.append(pt)
        html = html.replace(pt, en)
    if faltando:
        raise ValueError("Trechos da tradução que não existem mais no home.html:\n- " + "\n- ".join(f[:90] for f in faltando))
    return html
